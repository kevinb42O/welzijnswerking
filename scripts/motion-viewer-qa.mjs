import { chromium, webkit, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const engine = process.env.QA_BROWSER || 'chromium';
const browser = await ({chromium,webkit})[engine].launch();
const base = process.env.QA_URL || 'http://127.0.0.1:4325/';
const folder = `qa/motion-polish-2026-10-20/${engine}`;
await mkdir(folder,{recursive:true});
const report=[];
try {
  const context = await browser.newContext({viewport:{width:390,height:844}});
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base);
  await page.route('**/2025-facebook-07-1536.webp',async route=>{await new Promise(resolve=>setTimeout(resolve,900));await route.continue();});
  await page.locator('[data-photo-open]').first().click();
  const dialog=page.locator('#event-lightbox');
  const image=dialog.locator('.photo-viewer-stage img');
  await expect(image).toBeVisible();
  await expect(dialog.locator('figcaption')).toContainText('1 /');
  const initialSrc=await image.getAttribute('src');
  const initialHeight=await dialog.locator('.photo-viewer-stage').evaluate(el=>el.offsetHeight);
  await page.keyboard.press('ArrowRight');
  await expect(dialog.locator('.photo-viewer-stage')).toHaveAttribute('aria-busy','true');
  await page.waitForTimeout(200);
  await expect(image).toBeVisible();
  assert.equal(await image.getAttribute('src'),initialSrc,'Existing photo remains visible during a delayed load');
  assert.equal(await dialog.locator('.photo-viewer-stage').evaluate(el=>el.offsetHeight),initialHeight,'Loading never moves the stage');
  await expect(dialog.locator('figcaption')).toContainText('2 /');
  const loadedSrc=await image.getAttribute('src');
  await page.route('**/2025-facebook-01-1536.webp',route=>route.abort());
  await page.keyboard.press('ArrowRight');
  await expect(dialog.locator('.photo-viewer-status')).toContainText('niet worden geladen');
  assert.equal(await image.getAttribute('src'),loadedSrc,'Failed load keeps the last good photo');
  await page.keyboard.press('ArrowRight');
  await expect(dialog.locator('figcaption')).toContainText('4 /');
  await expect(dialog.locator('.photo-viewer-status')).toBeEmpty();
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(page.locator('[data-photo-open]').first()).toBeFocused();
  report.push({viewer:{slowLoadKeepsImage:true,stableStage:true,errorKeepsImage:true,recovery:true,focusRestore:true}});
  await page.goto(base);
  const frame=page.locator('[data-motion-frame]').first();
  await frame.evaluate(el=>scrollTo({top:scrollY+el.getBoundingClientRect().top-innerHeight*.6,behavior:'instant'}));
  await page.waitForTimeout(120);
  await page.emulateMedia({reducedMotion:'reduce'});
  await expect.poll(()=>page.locator('[data-motion-surface]').evaluateAll(elements=>elements.every(el=>!el.style.transform&&!el.style.opacity&&!el.style.willChange))).toBe(true);
  report.push({liveReducedMotion:{allPendingAndActiveStylesCleared:true}});
  await page.goto(base);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await frame.evaluate(el=>scrollTo({top:scrollY+el.getBoundingClientRect().top-innerHeight*.6,behavior:'instant'}));
  await page.waitForTimeout(120);
  await page.setViewportSize({width:844,height:390});
  await expect.poll(()=>frame.locator('[data-motion-surface]').evaluate(el=>el.style.transform)).toBe('');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  report.push({rotation:{activeMotionSettles:true,noHorizontalOverflow:true},pageErrors:errors});
  await context.close();
  await writeFile(`${folder}/viewer-results.json`,JSON.stringify(report,null,2));
  console.log(JSON.stringify({engine,passed:true,report}));
} finally {await browser.close();}
