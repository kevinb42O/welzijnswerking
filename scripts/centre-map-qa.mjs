import { chromium, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const base = process.env.QA_URL || 'http://127.0.0.1:4323/';
const output = 'qa/centres-map-2026-10-21';
await mkdir(output, { recursive: true });
const browser = await chromium.launch();
const report = { layouts: [], errors: [] };
try {
  for (const width of [320, 390, 768, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    page.on('pageerror', e => report.errors.push(e.message));
    const requests = [];
    page.on('request', req => { if (req.url().includes('geo.api.vlaanderen.be/GRB/wmts')) requests.push(req.url()); });
    await page.goto(base + '#ontmoetingscentra');
    await page.evaluate(() => document.fonts.ready);
    const map = page.locator('[data-centre-map]');
    assert.equal(requests.length, 0, 'Map tiles must not load before user opens map');
    await expect(map).not.toHaveAttribute('open');
    if (await map.isVisible()) await map.locator('summary').click();
    else await page.locator('[data-show-map]').click();
    await expect(page.locator('.centre-map-marker')).toHaveCount(9);
    await expect(page.locator('.leaflet-tile-loaded').first()).toBeVisible({ timeout: 20000 });
    await expect(page.locator('[data-map-status]')).toBeHidden();
    await page.locator('[data-map-choice]').selectOption('kasteeltje');
    await expect(page.locator('[data-map-name]')).toHaveText('’t Kasteeltje');
    await expect(page.locator('[data-map-street]')).toHaveText('Kasteelstraat 22b');
    await expect(page.locator('[data-map-phone]')).toHaveAttribute('href', 'tel:059259127');
    await expect(page.locator('[data-map-route]')).toHaveAttribute('href', /Kasteeltje/);
    const marker = page.getByRole('button', { name: 'Toon De Boeie, Centrum', exact: true });
    await page.locator('[data-map-reset]').click();
    await marker.focus();
    await page.keyboard.press('Enter');
    await expect(page.locator('[data-map-name]')).toHaveText('De Boeie');
    await page.keyboard.press('Space');
    await expect(page.locator('[data-map-name]')).toHaveText('De Boeie');
    await expect(marker).toHaveAttribute('aria-pressed', 'true');
    await page.locator('[data-map-choice]').selectOption('de-ballon');
    await expect(page.locator('[data-map-name]')).toHaveText('De Ballon');
    await page.locator('[data-map-reset]').click();
    await page.getByRole('button', { name: 'Inzoomen', exact: true }).click();
    await page.getByRole('button', { name: 'Uitzoomen', exact: true }).click();
    if (await map.isVisible()) await map.locator('summary').click();
    else await page.locator('[data-show-map]').click();
    await expect(map).not.toHaveAttribute('open');
    if (await map.isVisible()) await map.locator('summary').click();
    else await page.locator('[data-show-map]').click();
    await expect(page.locator('.centre-map-marker')).toHaveCount(9);
    await page.locator('[data-map-reset]').click();
    await page.locator('[data-map-choice]').selectOption('de-boeie');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const axe = await new AxeBuilder({ page }).include('#ontmoetingscentra').withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa']).analyze();
    assert.deepEqual(axe.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))})), []);
    await page.waitForFunction(() => [...document.querySelectorAll('.leaflet-tile')].every(image => image.complete && image.naturalWidth > 0));
    await map.scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${output}/viewport-${width}.png` });
    await map.screenshot({ path: `${output}/map-${width}.png` });
    report.layouts.push({width, markers:9, delayedLoading:true, keyboardSelection:true, selection:true, reset:true, reopen:true, overflow:false, axeViolations:0, tiles:requests.length});
    await context.close();
  }
  const context = await browser.newContext({viewport:{width:390,height:900},reducedMotion:'reduce'});
  const page = await context.newPage();
  await page.route('https://geo.api.vlaanderen.be/GRB/wmts?**', route=>route.abort());
  await page.goto(base+'#ontmoetingscentra');
  await page.locator('[data-show-map]').click();
  await expect(page.locator('[data-map-status]')).toContainText('achtergrondkaart kan niet laden');
  await page.locator('[data-map-choice]').selectOption('ter-yde');
  await expect(page.locator('[data-map-name]')).toHaveText('Ter Yde');
  await page.locator('[data-centre-map]').screenshot({path:`${output}/map-offline.png`});
  report.tileFailureRecovery = true;
  await context.close();
  const touchContext = await browser.newContext({ viewport: { width:390,height:900 }, isMobile:true, hasTouch:true, reducedMotion:'reduce' });
  const touchPage = await touchContext.newPage();
  await touchPage.goto(base+'#ontmoetingscentra');
  await touchPage.locator('[data-show-map]').click();
  await expect(touchPage.locator('.centre-map-marker')).toHaveCount(9);
  await touchPage.locator('[data-map-canvas]').scrollIntoViewIfNeeded();
  const rect = await touchPage.locator('[data-map-canvas]').boundingBox();
  const client = await touchContext.newCDPSession(touchPage);
  const before = await touchPage.locator('.centre-map-marker').first().evaluate(e => e.style.transform);
  const fingers = [{x:rect.x+100,y:rect.y+120,id:0},{x:rect.x+200,y:rect.y+120,id:1}];
  await client.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:fingers});
  await client.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:fingers.map(p=>({...p,y:p.y+50}))});
  await client.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await touchPage.waitForTimeout(100);
  const after = await touchPage.locator('.centre-map-marker').first().evaluate(e => e.style.transform);
  assert.notEqual(before,after,'Two-finger map panning must work');
  await touchPage.evaluate(()=>{ document.documentElement.style.fontSize='200%'; });
  assert.equal(await touchPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  report.touchPan = true;
  report.enlargedText = true;
  await touchContext.close();
  const noJs = await browser.newContext({ javaScriptEnabled: false, viewport:{width:390,height:900} });
  const noJsPage = await noJs.newPage();
  await noJsPage.goto(base);
  await expect(noJsPage.locator('.centre-phone')).toHaveCount(9);
  await noJsPage.locator('[data-centre-map] summary').click();
  await expect(noJsPage.locator('[data-centre-map] noscript p')).toBeVisible();
  report.noJavaScript = true;
  await noJs.close();
  assert.deepEqual(report.errors, []);
} finally { await browser.close(); await writeFile(`${output}/report.json`, JSON.stringify(report,null,2)+'\n'); }
console.log(JSON.stringify(report,null,2));
